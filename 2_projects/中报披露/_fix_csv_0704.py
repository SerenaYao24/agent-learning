# 读取现有CSV
rows = []
codes = set()
with open(CSV_PATH, 'r', encoding='utf-8') as f:
    reader = csv.reader(f)
    for i, row in enumerate(reader):
        rows.append(row)
        if i > 0 and len(row) >= 3:
            import re
            m = re.search(r'（(\d{6})）', row[2])
            if m:
                codes.add(m.group(1))

header = rows[0]  # 15列
data = rows[1:]

# 清空旧 "最新披露"
for r in data:
    if len(r) > 13:
        r[13] = ''

# 去重加入新数据
added = 0
for n in NEW:
    import re
    m = re.search(r'（(\d{6})）', n[2])
    code = m.group(1) if m else ''
    if code not in codes:
        # 补齐15列
        while len(n) < 15:
            n.append('')
        data.append(n)
        codes.add(code)
        added += 1

# 按市值排序
def sort_key(r):
    m = re.search(r'~(\d+)亿', r[2] if len(r) > 2 else '')
    return -int(m.group(1)) if m else 0

data.sort(key=sort_key)

# 写回
with open(CSV_PATH, 'w', encoding='utf-8', newline='') as f:
    writer = csv.writer(f)
    writer.writerow(header)
    for r in data:
        writer.writerow(r)

print(f'CSV修复完成：共{len(data)}条数据，新增{added}只')
